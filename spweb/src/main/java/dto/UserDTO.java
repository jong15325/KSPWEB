	public void setEmptySlot(List<UserCardDTO> cardList, int usr_nslots) {
		int cardEmptySlot = 0;
		int cardListIndex = 0;
		int inventoryValue[] = new int[usr_nslots];
		for (int i = 0; i < usr_nslots; i++) {
			if(cardList.size() == 0) {
				break;
			}else {
				if(i != cardList.get(cardListIndex).getItm_slot()) {
					inventoryValue[i] = -1;
					cardEmptySlot = i;
					break;
				}else {
					inventoryValue[i] = cardList.get(cardListIndex).getItm_slot();
				}
				if(cardListIndex + 1 < cardList.size())
					cardListIndex++;
			}
		}
		this.emptySlot = cardEmptySlot;
	}

